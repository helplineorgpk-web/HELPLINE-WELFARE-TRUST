export function getSection(id) {
  return DAILY_NEWS_SECTIONS[id] || null;
}

export function getAllDailyUpdates() {
  const categoryRank = Object.fromEntries(
    NEWS_CATEGORY_ORDER.map((key, index) => [key, index])
  );

  const updates = [];
  Object.values(DAILY_NEWS_SECTIONS).forEach((section) => {
    section.dailyUpdates?.forEach((update) => {
      updates.push({
        ...update,
        sectionId: section.id,
        sectionTitle: section.cardTag || section.title,
        category: section.category || "other",
      });
    });
  });

  return updates.sort((a, b) => {
    const aFirst = a.pinFirst ? 1 : 0;
    const bFirst = b.pinFirst ? 1 : 0;
    if (aFirst !== bFirst) return bFirst - aFirst;
    const aSecond = a.pinSecond ? 1 : 0;
    const bSecond = b.pinSecond ? 1 : 0;
    if (aSecond !== bSecond) return bSecond - aSecond;
    const catDiff =
      (categoryRank[a.category] ?? 99) - (categoryRank[b.category] ?? 99);
    if (catDiff !== 0) return catDiff;
    const aStart = a.pinStart ? 1 : 0;
    const bStart = b.pinStart ? 1 : 0;
    if (aStart !== bStart) return bStart - aStart;
    const aEnd = a.pinEnd ? 1 : 0;
    const bEnd = b.pinEnd ? 1 : 0;
    if (aEnd !== bEnd) return aEnd - bEnd;
    const da = new Date(`${a.date} ${a.time}`);
    const db = new Date(`${b.date} ${b.time}`);
    return db - da;
  });
}

export function getUpdatesByCategory() {
  const grouped = Object.fromEntries(
    NEWS_CATEGORY_ORDER.map((key) => [key, []])
  );

  getAllDailyUpdates().forEach((update) => {
    const key = NEWS_CATEGORY_ORDER.includes(update.category)
      ? update.category
      : "other";
    grouped[key].push(update);
  });

  return NEWS_CATEGORY_ORDER.map((key) => ({
    key,
    label: NEWS_CATEGORY_LABELS[key],
    updates: grouped[key],
  })).filter((group) => group.updates.length > 0);
}

export function getTickerHeadlines() {
  return getAllDailyUpdates().map(
    (u) => `${u.sectionTitle}: ${u.title}`
  );
}

export function getTickerItems() {
  return getAllDailyUpdates().map((u) => ({
    sectionId: u.sectionId,
    headline: `${u.sectionTitle}: ${u.title}`,
  }));
}

export function searchDailyNews(query) {
  const q = query.trim();
  if (!q) return [];

  const results = [];
  const seen = new Set();

  Object.values(DAILY_NEWS_SECTIONS).forEach((section) => {
    const sectionHaystack = [section.title, section.subtitle, section.summary, section.location]
      .filter(Boolean)
      .join(" ");

    if (sectionHaystack.includes(q) && !seen.has(section.id)) {
      seen.add(section.id);
      results.push({ type: "section", id: section.id, label: section.title });
    }

    section.dailyUpdates?.forEach((update) => {
      const updateHaystack = `${update.title} ${update.body}`;
      if (updateHaystack.includes(q) && !seen.has(`${section.id}-${update.title}`)) {
        seen.add(`${section.id}-${update.title}`);
        results.push({
          type: "update",
          id: section.id,
          label: update.title,
          sectionTitle: section.title,
        });
      }
    });
  });

  return results;
}

