/**
 * One-off compressor for /campaigns page images.
 *
 *  - Reads every `image:` path from data/campaignsData.js
 *  - Produces a compressed sibling in public/img/campaigns-opt/
 *  - Emits data/campaignImageAssets.json with the mapping + blurDataURL
 *
 * Run:  node scripts/optimize-campaign-images.js
 *
 * The campaign data file consumes campaignImageAssets.json at runtime, so
 * after re-running this script the /campaigns page automatically picks up
 * the new paths without any source edits.
 */
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

const ROOT = path.resolve(__dirname, "..");
const PUBLIC_DIR = path.join(ROOT, "public");
const OUT_DIR = path.join(PUBLIC_DIR, "img", "campaigns-opt");
const MANIFEST_JSON = path.join(ROOT, "data", "campaignImageAssets.json");
const MANIFEST_JS = path.join(ROOT, "data", "campaignImageAssets.js");

const MAX_WIDTH = 1280;
const WEBP_QUALITY = 72;
const BLUR_WIDTH = 16;
const BLUR_QUALITY = 40;

function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}

function slug(p) {
  return p
    .replace(/^\/+/, "")
    .replace(/[^\w.\-]+/g, "_")
    .replace(/\.(png|jpe?g|webp)$/i, "")
    .toLowerCase();
}

async function compressOne(publicPath) {
  const srcAbs = path.join(PUBLIC_DIR, publicPath);
  if (!fs.existsSync(srcAbs)) {
    console.warn("  skip (missing):", publicPath);
    return null;
  }

  const outName = `${slug(publicPath)}.webp`;
  const outAbs = path.join(OUT_DIR, outName);
  const outPublic = `/img/campaigns-opt/${outName}`;

  const pipeline = sharp(srcAbs).rotate();
  const meta = await pipeline.metadata();
  const targetWidth = Math.min(meta.width || MAX_WIDTH, MAX_WIDTH);

  await pipeline
    .resize({ width: targetWidth, withoutEnlargement: true })
    .webp({ quality: WEBP_QUALITY, effort: 5 })
    .toFile(outAbs);

  const blurBuf = await sharp(srcAbs)
    .rotate()
    .resize({ width: BLUR_WIDTH })
    .webp({ quality: BLUR_QUALITY })
    .toBuffer();
  const blurDataURL = `data:image/webp;base64,${blurBuf.toString("base64")}`;

  const srcSize = fs.statSync(srcAbs).size;
  const outSize = fs.statSync(outAbs).size;
  const pct = Math.round((outSize / srcSize) * 100);
  console.log(
    `  ${publicPath}  ->  ${outPublic}  (${(srcSize / 1024).toFixed(0)}KB -> ${(
      outSize / 1024
    ).toFixed(0)}KB, ${pct}%)`
  );

  return { optimized: outPublic, blurDataURL };
}

async function main() {
  ensureDir(OUT_DIR);

  const campaignsDataPath = path.join(ROOT, "data", "campaignsData.js");
  const src = fs.readFileSync(campaignsDataPath, "utf8");
  const imageMatches = [...src.matchAll(/image:\s*"([^"]+)"/g)].map(
    (m) => m[1]
  );
  const unique = [...new Set(imageMatches)];

  console.log(`Found ${unique.length} unique image paths.\n`);

  const manifest = {};
  for (const p of unique) {
    try {
      const res = await compressOne(p);
      if (res) manifest[p] = res;
    } catch (err) {
      console.error("  error on", p, err.message);
    }
  }

  fs.writeFileSync(MANIFEST_JSON, JSON.stringify(manifest, null, 2));
  const header =
    "// Auto-generated by scripts/optimize-campaign-images.js — do not edit by hand.\n";
  fs.writeFileSync(
    MANIFEST_JS,
    `${header}const campaignImageAssets = ${JSON.stringify(
      manifest,
      null,
      2
    )};\n\nexport default campaignImageAssets;\n`
  );
  console.log(
    `\nWrote manifest: ${path.relative(ROOT, MANIFEST_JS)}  (${
      Object.keys(manifest).length
    } entries)`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
