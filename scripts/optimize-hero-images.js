/**
 * Hero image optimizer.
 *
 * Walks a curated list of hero image folders (Campaigns/*, bg/breadcrum*),
 * produces a resized WebP sibling in public/img/hero-opt/, and emits a manifest
 * at data/heroImageAssets.js that maps original path -> {optimized, blurDataURL}.
 *
 * The hero <Image> components read this manifest through lib/heroImage.js and
 * fall back to the original src when no entry is present, so it is always safe
 * to re-run (or skip) this script.
 *
 * Run:  npm run optimize:hero-images
 */
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

const ROOT = path.resolve(__dirname, "..");
const PUBLIC_DIR = path.join(ROOT, "public");
const OUT_DIR = path.join(PUBLIC_DIR, "img", "hero-opt");
const DATA_DIR = path.join(ROOT, "data");
const MANIFEST_JSON = path.join(DATA_DIR, "heroImageAssets.json");
const MANIFEST_JS = path.join(DATA_DIR, "heroImageAssets.js");

const MAX_WIDTH = 1920;
const WEBP_QUALITY = 72;
const BLUR_WIDTH = 16;
const BLUR_QUALITY = 40;

const SOURCE_GLOBS = [
  { dir: path.join(PUBLIC_DIR, "img", "Campaigns"), match: /\.(webp|jpe?g|png)$/i },
  {
    dir: path.join(PUBLIC_DIR, "img", "bg"),
    match: /^(breadcrum|breadcrumb|cta_bg|donate_bg|video_bg|animated|event_bg)[^/]*\.(webp|jpe?g|png)$/i,
  },
];

function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}

function toPublicPath(absPath) {
  return "/" + path.relative(PUBLIC_DIR, absPath).split(path.sep).join("/");
}

function slug(p) {
  return p
    .replace(/^\/+/, "")
    .replace(/[^\w.\-]+/g, "_")
    .replace(/\.(png|jpe?g|webp)$/i, "")
    .toLowerCase();
}

function walk(dir, match) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => match.test(f))
    .map((f) => path.join(dir, f));
}

async function compressOne(absSrc) {
  const publicPath = toPublicPath(absSrc);
  const outName = `${slug(publicPath)}.webp`;
  const outAbs = path.join(OUT_DIR, outName);
  const outPublic = `/img/hero-opt/${outName}`;

  const pipeline = sharp(absSrc).rotate();
  const meta = await pipeline.metadata();
  const targetWidth = Math.min(meta.width || MAX_WIDTH, MAX_WIDTH);

  await pipeline
    .resize({ width: targetWidth, withoutEnlargement: true })
    .webp({ quality: WEBP_QUALITY, effort: 5 })
    .toFile(outAbs);

  const blurBuf = await sharp(absSrc)
    .rotate()
    .resize({ width: BLUR_WIDTH })
    .webp({ quality: BLUR_QUALITY })
    .toBuffer();
  const blurDataURL = `data:image/webp;base64,${blurBuf.toString("base64")}`;

  const srcSize = fs.statSync(absSrc).size;
  const outSize = fs.statSync(outAbs).size;
  const pct = Math.round((outSize / srcSize) * 100);
  console.log(
    `  ${publicPath}  ->  ${outPublic}  (${(srcSize / 1024).toFixed(0)}KB -> ${(
      outSize / 1024
    ).toFixed(0)}KB, ${pct}%)`
  );

  return { publicPath, optimized: outPublic, blurDataURL };
}

async function main() {
  ensureDir(OUT_DIR);
  ensureDir(DATA_DIR);

  const targets = [];
  for (const { dir, match } of SOURCE_GLOBS) {
    targets.push(...walk(dir, match));
  }

  console.log(`Found ${targets.length} hero image candidates.\n`);

  const manifest = {};
  for (const abs of targets) {
    try {
      const res = await compressOne(abs);
      manifest[res.publicPath] = {
        optimized: res.optimized,
        blurDataURL: res.blurDataURL,
      };
    } catch (err) {
      console.error("  error on", abs, err.message);
    }
  }

  fs.writeFileSync(MANIFEST_JSON, JSON.stringify(manifest, null, 2));
  const header =
    "// Auto-generated by scripts/optimize-hero-images.js - do not edit by hand.\n";
  fs.writeFileSync(
    MANIFEST_JS,
    `${header}const heroImageAssets = ${JSON.stringify(
      manifest,
      null,
      2
    )};\n\nexport default heroImageAssets;\n`
  );
  console.log(
    `\nWrote manifest: ${path.relative(ROOT, MANIFEST_JS)}  (${
      Object.keys(manifest).length
    } entries)`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
